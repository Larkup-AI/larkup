import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const benchmark = fileURLToPath(new URL('../../../../../', import.meta.url));
const root = resolve(benchmark, '../../../workspace-server');
const require = createRequire(resolve(root, 'package.json'));
const { generateText } = await import(pathToFileURL(require.resolve('ai')));
const { createChatModel } = await import(pathToFileURL(resolve(root, 'src/lib/chat/model-provider.ts')));
let input = ''; for await (const chunk of process.stdin) input += chunk;
const data = JSON.parse(input);
const result = await generateText({model:createChatModel('vercel_ai_gateway', data.model, data.apiKey), messages:[{role:'user',content:data.prompt}], temperature:0, reasoning:'none', maxOutputTokens:4096, maxRetries:0, abortSignal:AbortSignal.timeout(90000)});
process.stdout.write(JSON.stringify({answer:result.text, usage:result.usage, finishReason:result.finishReason}));
